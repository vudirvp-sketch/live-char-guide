#!/usr/bin/env node
/**
 * Sitemap generator — writes /sitemap.xml (copied to dist/ by the shell build).
 *
 * WHY: the sitemap was a hand-maintained 4-line file with a single URL and no
 * <lastmod>. It is now generated, so it cannot drift from the build, and it is
 * already shaped for the two known future additions:
 *
 *   1. per-chapter landing pages (docs/PROMOTION_PLAN.md D-2) — push URLs into
 *      CHAPTER_PAGES and they are emitted with priority/lastmod;
 *   2. a second language (docs/I18N_PLAN.md) — add the /en/ URL and hreflang
 *      alternates here, not in a second script.
 *
 * IMPORTANT: only real, separately-addressable URLs belong here. `#anchor`
 * fragments are not URLs and must never be listed — that is the mistake this
 * file exists to prevent.
 *
 * Usage: node scripts/generate-sitemap.mjs
 */

import { readFile, writeFile } from 'fs/promises';
import { existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { SITE, absoluteUrl } from './site-config.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SITEMAP = join(ROOT, 'sitemap.xml');
const VERSION_FILE = join(ROOT, 'src', 'VERSION');

/**
 * Future chapter landing pages go here (D-2). Shape:
 *   { path: 'ch/spine/', priority: '0.9' }
 * Empty today on purpose: no such pages are deployed yet, and a sitemap must not
 * advertise 404s.
 */
const CHAPTER_PAGES = [];

function escapeXml(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function urlEntry({ loc, lastmod, changefreq, priority }) {
  const lines = [`    <loc>${escapeXml(loc)}</loc>`];
  if (lastmod) lines.push(`    <lastmod>${lastmod}</lastmod>`);
  if (changefreq) lines.push(`    <changefreq>${changefreq}</changefreq>`);
  if (priority) lines.push(`    <priority>${priority}</priority>`);
  return `  <url>\n${lines.join('\n')}\n  </url>`;
}

async function main() {
  const buildDate = new Date().toISOString().slice(0, 10);

  let version = 'unknown';
  if (existsSync(VERSION_FILE)) {
    version = (await readFile(VERSION_FILE, 'utf-8')).trim();
  }

  const entries = [
    {
      loc: SITE.url,
      lastmod: buildDate,
      changefreq: 'weekly',
      priority: '1.0',
    },
    ...CHAPTER_PAGES.map((page) => ({
      loc: absoluteUrl(page.path),
      lastmod: buildDate,
      changefreq: 'monthly',
      priority: page.priority ?? '0.8',
    })),
  ];

  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<!-- Generated by scripts/generate-sitemap.mjs — guide v${version}. Do not hand-edit. -->`,
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...entries.map(urlEntry),
    '</urlset>',
    '',
  ].join('\n');

  await writeFile(SITEMAP, xml, 'utf-8');
  console.log(`✓ sitemap.xml written: ${entries.length} URL(s), site ${SITE.url}`);
}

main().catch((error) => {
  console.error('❌ sitemap generation failed:', error.message);
  process.exit(1);
});
