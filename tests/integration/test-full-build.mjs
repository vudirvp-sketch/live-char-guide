#!/usr/bin/env node
/**
 * @fileoverview Integration tests for full build pipeline (unified)
 * @module tests/integration/test-full-build
 * @version 3.0.0
 * 
 * @description
 * Tests for unified guide architecture:
 * - Source files in src/unified/ (unified HTML parts)
 * - Build intermediate in build/parts/
 * - Build output in dist-unified/ (or dist/)
 * - Root deployment files for GitHub Pages compatibility
 * 
 * Migrated from L1/L2/L3 layer system to unified linear guide per Phase 6.7.
 */

import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, stat } from 'fs/promises';
import { existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');

// ============================================================================
// SOURCE FILES TESTS
// ============================================================================

describe('Source Files Structure', () => {
  it('should have src directory', () => {
    const srcDir = join(ROOT, 'src');
    assert.strictEqual(existsSync(srcDir), true, 'src/ directory should exist');
  });

  it('should have src/unified directory (source HTML parts)', () => {
    const unifiedDir = join(ROOT, 'src', 'unified');
    assert.strictEqual(existsSync(unifiedDir), true, 'src/unified/ directory should exist');
  });

  it('should have build/parts directory (generated by build-unified.mjs)', () => {
    const partsDir = join(ROOT, 'build', 'parts');
    assert.strictEqual(existsSync(partsDir), true, 'build/parts/ directory should exist after build');
  });

  it('should have shell-unified directory', () => {
    const shellDir = join(ROOT, 'src', 'shell-unified');
    assert.strictEqual(existsSync(shellDir), true, 'src/shell-unified/ directory should exist');
  });

  it('should have manifest.json in build/parts', () => {
    const manifestPath = join(ROOT, 'build', 'parts', 'manifest.json');
    assert.strictEqual(existsSync(manifestPath), true, 'build/parts/manifest.json should exist after build');
  });
});

// ============================================================================
// BUILD OUTPUT TESTS
// ============================================================================

describe('Build Output', () => {
  it('should generate valid dist-unified/index.html (or dist/index.html)', async () => {
    const distUnifiedPath = join(ROOT, 'dist-unified', 'index.html');
    const distPath = join(ROOT, 'dist', 'index.html');
    const indexPath = existsSync(distUnifiedPath) ? distUnifiedPath : distPath;

    if (existsSync(indexPath)) {
      const content = await readFile(indexPath, 'utf-8');

      assert.ok(content.startsWith('<!DOCTYPE html>'), 'Should have DOCTYPE');
      assert.ok(content.includes('<html'), 'Should have html tag');
      assert.ok(content.includes('</html>'), 'Should close html tag');
    }
  });

  it('should have dist-unified/parts directory (or dist/parts)', () => {
    const distUnifiedParts = join(ROOT, 'dist-unified', 'parts');
    const distParts = join(ROOT, 'dist', 'parts');
    const partsDir = existsSync(distUnifiedParts) ? distUnifiedParts : distParts;
    assert.strictEqual(existsSync(partsDir), true, 'dist-unified/parts/ or dist/parts/ should exist after build');
  });

  it('should have dist-unified/assets directory (or dist/assets)', () => {
    const distUnifiedAssets = join(ROOT, 'dist-unified', 'assets');
    const distAssets = join(ROOT, 'dist', 'assets');
    const assetsDir = existsSync(distUnifiedAssets) ? distUnifiedAssets : distAssets;
    assert.strictEqual(existsSync(assetsDir), true, 'dist-unified/assets/ or dist/assets/ should exist after build');
  });

  it('should have lazy-loader.js in dist assets', () => {
    const distUnifiedLazy = join(ROOT, 'dist-unified', 'assets', 'lazy-loader.js');
    const distLazy = join(ROOT, 'dist', 'assets', 'lazy-loader.js');
    const lazyPath = existsSync(distUnifiedLazy) ? distUnifiedLazy : distLazy;
    assert.strictEqual(existsSync(lazyPath), true, 'lazy-loader.js should exist in dist assets');
  });

  it('should have shell-styles.css in dist assets', () => {
    const distUnifiedStyles = join(ROOT, 'dist-unified', 'assets', 'shell-styles.css');
    const distStyles = join(ROOT, 'dist', 'assets', 'shell-styles.css');
    const stylesPath = existsSync(distUnifiedStyles) ? distUnifiedStyles : distStyles;
    assert.strictEqual(existsSync(stylesPath), true, 'shell-styles.css should exist in dist assets');
  });
});

// ============================================================================
// ROOT FALLBACK FILES TESTS (CI Compatibility)
// ============================================================================

describe('Root Fallback Files', () => {
  it('should have index.html in root', () => {
    const indexPath = join(ROOT, 'index.html');
    assert.strictEqual(existsSync(indexPath), true, 'index.html should exist in root (fallback)');
  });

  it('should have build.hash in root', () => {
    const hashPath = join(ROOT, 'build.hash');
    assert.strictEqual(existsSync(hashPath), true, 'build.hash should exist in root (fallback)');
  });

  it('should have assets directory in root', () => {
    const assetsDir = join(ROOT, 'assets');
    assert.strictEqual(existsSync(assetsDir), true, 'assets/ should exist in root (fallback)');
  });

  it('should have parts directory in root (unified)', () => {
    const partsDir = join(ROOT, 'parts');
    assert.strictEqual(existsSync(partsDir), true, 'parts/ should exist in root (unified fallback)');
  });

  it('root index.html should match dist index.html', async () => {
    const rootIndex = join(ROOT, 'index.html');
    const distUnifiedIndex = join(ROOT, 'dist-unified', 'index.html');
    const distIndex = join(ROOT, 'dist', 'index.html');
    const distRef = existsSync(distUnifiedIndex) ? distUnifiedIndex : distIndex;
    
    if (existsSync(rootIndex) && existsSync(distRef)) {
      const rootContent = await readFile(rootIndex, 'utf-8');
      const distContent = await readFile(distRef, 'utf-8');
      assert.strictEqual(rootContent, distContent, 'Root index.html should match dist index.html');
    }
  });
});

// ============================================================================
// BUILD HASH CONSISTENCY TESTS
// ============================================================================

describe('Build Hash Consistency', () => {
  it('should have build.hash file in dist', () => {
    const distUnifiedHash = join(ROOT, 'dist-unified', 'build.hash');
    const distHash = join(ROOT, 'dist', 'build.hash');
    const hashPath = existsSync(distUnifiedHash) ? distUnifiedHash : distHash;
    assert.strictEqual(existsSync(hashPath), true, 'build.hash should exist in dist');
  });

  it('build.hash should match dist index.html meta', async () => {
    const distUnifiedHash = join(ROOT, 'dist-unified', 'build.hash');
    const distHash = join(ROOT, 'dist', 'build.hash');
    const hashPath = existsSync(distUnifiedHash) ? distUnifiedHash : distHash;

    const distUnifiedIndex = join(ROOT, 'dist-unified', 'index.html');
    const distIndex = join(ROOT, 'dist', 'index.html');
    const indexPath = existsSync(distUnifiedIndex) ? distUnifiedIndex : distIndex;

    if (existsSync(hashPath) && existsSync(indexPath)) {
      const hash = (await readFile(hashPath, 'utf-8')).trim();
      const content = await readFile(indexPath, 'utf-8');

      assert.ok(content.includes(`Build: ${hash}`),
        'dist index.html should contain matching build hash');
    }
  });
});

// ============================================================================
// UNIFIED MANIFEST TESTS
// ============================================================================

describe('Unified Manifest', () => {
  it('build/parts/manifest.json should have unified format', async () => {
    const manifestPath = join(ROOT, 'build', 'parts', 'manifest.json');
    if (existsSync(manifestPath)) {
      const manifest = JSON.parse(await readFile(manifestPath, 'utf-8'));

      assert.strictEqual(manifest.format, 'unified', 'Manifest format should be "unified"');
      assert.ok(manifest.version, 'Manifest should have version');
      assert.ok(Array.isArray(manifest.parts), 'Manifest should have parts array');
      assert.ok(manifest.parts.length > 0, 'Parts array should not be empty');
    }
  });

  it('manifest should NOT have layer-specific fields', async () => {
    const manifestPath = join(ROOT, 'build', 'parts', 'manifest.json');
    if (existsSync(manifestPath)) {
      const manifest = JSON.parse(await readFile(manifestPath, 'utf-8'));

      assert.strictEqual(manifest.layer, undefined, 'Manifest should NOT have "layer" field');
      assert.strictEqual(manifest.name, undefined, 'Manifest should NOT have "name" field');
      assert.strictEqual(manifest.label, undefined, 'Manifest should NOT have "label" field');
      assert.strictEqual(manifest.color, undefined, 'Manifest should NOT have "color" field');
      assert.strictEqual(manifest.inherits, undefined, 'Manifest should NOT have "inherits" field');
    }
  });
});

// ============================================================================
// VALIDATION INTEGRATION TESTS
// ============================================================================

describe('Validation Integration', () => {
  it('validate script should pass', () => {
    try {
      execSync('node scripts/validate-artifact.mjs', {
        cwd: ROOT,
        stdio: 'pipe',
        timeout: 30000
      });
    } catch (error) {
      assert.fail(`Validation failed: ${error.stdout?.toString() || error.message}`);
    }
  });
});

// ============================================================================
// VERSION SYNC INTEGRATION TESTS
// ============================================================================

describe('Version Sync Integration', () => {
  it('all versions should be synchronized', async () => {
    const versionPath = join(ROOT, 'src', 'VERSION');
    const packagePath = join(ROOT, 'package.json');

    const distUnifiedIndex = join(ROOT, 'dist-unified', 'index.html');
    const distIndex = join(ROOT, 'dist', 'index.html');
    const indexPath = existsSync(distUnifiedIndex) ? distUnifiedIndex : distIndex;

    if (!existsSync(versionPath)) {
      return; // Skip if no VERSION file
    }

    const expectedVersion = (await readFile(versionPath, 'utf-8')).trim();

    // Check package.json
    if (existsSync(packagePath)) {
      const pkg = JSON.parse(await readFile(packagePath, 'utf-8'));
      assert.strictEqual(pkg.version, expectedVersion, 'package.json version mismatch');
    }

    // Check dist index.html
    if (existsSync(indexPath)) {
      const content = await readFile(indexPath, 'utf-8');
      const match = content.match(/<meta name="livechar-version" content="([^"]+)"/);
      if (match) {
        assert.strictEqual(match[1], expectedVersion, 'dist index.html version mismatch');
      }
    }
  });
});

// ============================================================================
// RUN TESTS
// ============================================================================

console.log('Running full build integration tests (unified guide architecture)...\n');
